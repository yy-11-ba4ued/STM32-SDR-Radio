#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
图标图片 -> C 头文件 转换工具（单色 1bpp）
==========================================
用法 1（推荐）：把 PNG/BMP/JPG 图片直接拖到本 .py 文件图标上
用法 2：命令行  python bitmap_to_c.py  图片路径
用法 3：不带参数运行，会弹出文件选择窗口

生成结果：与图片同目录（或本脚本目录）下的 sideband_icon.h
把里面的内容发给 AI 即可替换边带指示器。

可调参数见下方 CONFIG 区域。
"""
import os
import sys

# ==================== CONFIG（按需修改）====================
TARGET_HEIGHT = 17      # 输出图标的目标高度(像素)，0 = 保持原图尺寸不缩放
THRESHOLD     = 96      # 亮度阈值 0-255，大于它算“点亮”(白)，否则为背景(黑)
AUTO_CROP     = True    # 是否自动裁掉四周空白黑边
INVERT        = False   # 若你的图是“黑图标白底”，设为 True
OUT_NAME      = "sideband_icon.h"
SYMBOL        = "sideband"   # 生成的数组/函数名前缀
# ===========================================================

def fail(msg):
    print("[错误] " + msg)
    try:
        import tkinter as tk
        from tkinter import messagebox
        r = tk.Tk(); r.withdraw()
        messagebox.showerror("bitmap_to_c", msg)
    except Exception:
        pass
    input("按回车键退出...")
    sys.exit(1)

def pick_image():
    if len(sys.argv) > 1:
        return sys.argv[1]
    try:
        import tkinter as tk
        from tkinter import filedialog
        r = tk.Tk(); r.withdraw()
        p = filedialog.askopenfilename(
            title="选择图标图片",
            filetypes=[("图片", "*.png *.bmp *.jpg *.jpeg *.gif"), ("所有文件", "*.*")])
        return p
    except Exception:
        return None

def main():
    try:
        from PIL import Image
    except ImportError:
        fail("缺少 Pillow 库，请先运行：pip install pillow")

    img_path = pick_image()
    if not img_path:
        fail("没有选择图片。")
    if not os.path.isfile(img_path):
        fail("找不到图片：%s" % img_path)

    img = Image.open(img_path).convert("L")  # 灰度

    if INVERT:
        img = Image.eval(img, lambda v: 255 - v)

    # 二值化
    bw = img.point(lambda v: 255 if v > THRESHOLD else 0, mode="1")

    if AUTO_CROP:
        bbox = bw.getbbox()
        if bbox:
            bw = bw.crop(bbox)
        else:
            fail("图片全黑，没有检测到图标内容。")

    # 按目标高度等比缩放（最近邻，保持锐利）
    w, h = bw.size
    if TARGET_HEIGHT and h != TARGET_HEIGHT:
        new_w = max(1, round(w * TARGET_HEIGHT / h))
        bw = bw.resize((new_w, TARGET_HEIGHT), Image.NEAREST)
        w, h = bw.size

    if w > 128 or h > 128:
        print("[警告] 尺寸较大(%dx%d)，边带指示器这种小图标建议高度 15~20px。" % (w, h))

    # 打包 1bpp，每行按字节对齐(MSB first)
    bytes_per_row = (w + 7) // 8
    rows = []
    lit = 0
    for y in range(h):
        row_bytes = []
        for b in range(bytes_per_row):
            byte = 0
            for bit in range(8):
                x = b * 8 + bit
                if x < w and bw.getpixel((x, y)):
                    byte |= (0x80 >> bit)
                    lit += 1
            row_bytes.append(byte)
        rows.append(row_bytes)

    # 生成 C 头文件
    W, Hh, BPR = SYMBOL.upper(), SYMBOL.upper(), SYMBOL.upper()
    lines = []
    lines.append("/* Auto-generated by bitmap_to_c.py */")
    lines.append("/* Source: %s */" % os.path.basename(img_path))
    lines.append("/* Size: %d x %d, 1bpp(MSB first), %d bytes/row, lit pixels=%d */"
                 % (w, h, bytes_per_row, lit))
    lines.append("#ifndef %s_ICON_H" % SYMBOL.upper())
    lines.append("#define %s_ICON_H" % SYMBOL.upper())
    lines.append("")
    lines.append("#define %s_ICON_W   %d" % (SYMBOL.upper(), w))
    lines.append("#define %s_ICON_H   %d" % (SYMBOL.upper(), h))
    lines.append("")
    lines.append("static const uint8_t %s_bits[%d][%d] = {"
                 % (SYMBOL, h, bytes_per_row))
    for r in rows:
        lines.append("  {" + ",".join("0x%02X" % b for b in r) + "},")
    lines.append("};")
    lines.append("")
    lines.append("/* Draw icon at (x,y) top-left with given color; level0 skipped. */")
    lines.append("static void ui_draw_%s(uint16_t x, uint16_t y, uint16_t color) {" % SYMBOL)
    lines.append("  for (int r = 0; r < %d; r++) {" % h)
    lines.append("    for (int c = 0; c < %d; c++) {" % w)
    lines.append("      if (%s_bits[r][c/8] & (0x80 >> (c%%8)))" % SYMBOL)
    lines.append("        lcd_draw_pixel(x+c, y+r, color);")
    lines.append("    }")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    lines.append("#endif")
    text = "\n".join(lines)

    out_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(out_dir, OUT_NAME)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)

    print("=" * 50)
    print("转换成功！")
    print("图标尺寸：%d x %d（宽 x 高）" % (w, h))
    print("点亮像素：%d" % lit)
    print("C 文件已生成：%s" % out_path)
    print("把该文件内容发给 AI 即可完成替换。")
    print("=" * 50)
    try:
        import tkinter as tk
        from tkinter import messagebox
        r = tk.Tk(); r.withdraw()
        messagebox.showinfo("完成", "已生成：\n%s\n尺寸 %dx%d" % (out_path, w, h))
    except Exception:
        pass
    input("按回车键退出...")

if __name__ == "__main__":
    main()
